"""Publish faithfully recorded MUSITU Axiom executions, never simulated responses."""
from __future__ import annotations
import html
import json
from pathlib import Path

SRC = Path(__file__).resolve().parents[1] / "content/axiom-verified-examples.json"
EXPECTED = ("finance.npv", "finance.var_historical", "statistics.regression", "optimization.linear_program")
LINK = "https://chatgpt.com/plugins/plugin_asdk_app_6ae058ee6cec81919329ae43b76a4c86"

def examples() -> list[dict]:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    assert data.get("version") == 1 and data.get("executed_at") == "2026-11-21"
    cases = data.get("cases")
    assert isinstance(cases, list) and tuple(x.get("operation") for x in cases) == EXPECTED
    assert all(x.get("input") and x.get("result") and x.get("summary") and x.get("prompt") for x in cases)
    assert cases[0]["verified"] is True and cases[-1]["verified"] is True
    assert cases[1]["verified"] is False and cases[2]["verified"] is False
    assert abs(cases[0]["result"]-11215.08093709444) < 1e-7
    assert abs(cases[1]["result"]["var"]-0.03245)<1e-10
    assert abs(cases[2]["result"]["slope"]-2.0083333333333333)<1e-10
    assert cases[3]["result"]["x"] == [2,2] and cases[3]["result"]["fun"] == -10
    return cases

def render_examples() -> str:
    esc=lambda x: html.escape(str(x),quote=True)
    cards=[]
    for c in examples():
        payload=json.dumps(c["input"],separators=(",",":"),ensure_ascii=False)
        trust=("Independently checked by Axiom" if c["verified"] else "Axiom execution result")
        cards.append(
          '<article class="axiom-proof-card" id="axiom-example-'+esc(c["id"])+'">'
          '<span class="eyebrow">ACTUAL AXIOM EXECUTION · 21 NOV 2026</span>'
          '<h3>'+esc(c["title"])+'</h3>'
          '<p class="axiom-proof-question">'+esc(c["question"])+'</p>'
          '<p class="axiom-proof-answer">'+esc(c["summary"])+'</p>'
          '<dl class="axiom-proof-meta">'
          '<div><dt>Operation</dt><dd><code>'+esc(c["operation"])+'</code></dd></div>'
          '<div><dt>Method</dt><dd>'+esc(c["method"])+'</dd></div>'
          '<div><dt>Interpretation</dt><dd>'+esc(c["interpretation"])+'</dd></div>'
          '</dl><details class="axiom-proof-details"><summary>View exact synthetic inputs and execution evidence</summary>'
          '<pre class="axiom-inputs"><code>'+esc(payload)+'</code></pre>'
          '<p>'+esc(c["verification"])+'</p></details>'
          '<div class="axiom-proof-actions">'
          '<a class="text-link" href="/resources/axiom-'+esc(c["id"])+'/">Read the worked tutorial ↗</a>'
          '<button type="button" class="axiom-copy-prompt" data-copy-axiom-prompt="'+esc(c["prompt"])+'">Copy example prompt</button>'
          '</div><span class="axiom-proof-state">'+trust+'</span></article>'
        )
    return (
      '<section class="section axiom-proof-section" id="axiom-real-examples"><div class="shell">'
      '<div class="section-heading"><span class="eyebrow">REAL CALCULATIONS, REAL RESULTS</span>'
      '<h2>See Axiom solve four practical problems.</h2>'
      '<p>Each worked example was executed using MUSITU Axiom on 21 November 2026. '
      'Inputs are synthetic and all outputs are recorded, not generated by this webpage.</p></div>'
      '<div class="axiom-proof-grid">'+''.join(cards)+'</div></div></section>'
    )

